function countryNames(): string[] {
  const display = new Intl.DisplayNames(['fr'], { type: 'region' });
  const names = REGION_CODES.map((code) => (display.of(code) ?? code).replace(/\u2019/g, "'"));
  return [...new Set(names)].sort((a, b) => a.localeCompare(b, 'fr'));
}

export const WORLD_COUNTRIES: string[] = countryNames();

export function countryOptions(current?: string | null): string[] {
  const name = (current ?? '').trim();
  if (name && !WORLD_COUNTRIES.includes(name)) {
    return [name, ...WORLD_COUNTRIES];
  }
  return WORLD_COUNTRIES;
}

export function mapZoomFor(precision?: string): number {
  if (precision === 'country') {
    return 6;
  }
  if (precision === 'city') {
    return 13;
  }
  return 16;
}

